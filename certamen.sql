SET NAMES utf8mb4;

CREATE TABLE administradores (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 usuario VARCHAR(64) NOT NULL UNIQUE,
 clave_hash VARCHAR(255) NOT NULL,
 proximo_intento BIGINT UNSIGNED NOT NULL DEFAULT 0,
 cambiar_clave TINYINT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE candidatos (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 nombre VARCHAR(120) NOT NULL,
 ciclo TINYINT UNSIGNED NOT NULL,
 categoria ENUM('miss','mister') NOT NULL,
 foto VARCHAR(100) NOT NULL,
 video VARCHAR(100) DEFAULT NULL,
 activo TINYINT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE fotos_candidato (
 candidato_id INT UNSIGNED NOT NULL,
 posicion TINYINT UNSIGNED NOT NULL,
 ruta VARCHAR(100) NOT NULL,
 PRIMARY KEY (candidato_id, posicion),
 FOREIGN KEY (candidato_id) REFERENCES candidatos(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE votantes (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 correo VARCHAR(254) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 codigo_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 miss_id INT UNSIGNED DEFAULT NULL,
 mister_id INT UNSIGNED DEFAULT NULL,
 CONSTRAINT fk_miss FOREIGN KEY (miss_id) REFERENCES candidatos(id),
 CONSTRAINT fk_mister FOREIGN KEY (mister_id) REFERENCES candidatos(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE configuracion (
 id TINYINT UNSIGNED PRIMARY KEY,
 abierta TINYINT UNSIGNED NOT NULL DEFAULT 0,
 cierre BIGINT UNSIGNED DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS historial_borrados (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 administrador_id INT UNSIGNED NOT NULL,
 usuario VARCHAR(64) NOT NULL,
 responsable VARCHAR(120) NOT NULL,
 instante BIGINT UNSIGNED NOT NULL,
 estudiantes INT UNSIGNED NOT NULL,
 votos_miss INT UNSIGNED NOT NULL,
 votos_mister INT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

